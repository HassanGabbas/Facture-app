let current = 'de';

export function setLang(lang) {
  current = DICT[lang] ? lang : 'de';
}

export function getLang() {
  return current;
}

export function t(key, params = {}) {
  const dict = DICT[current] || DICT.de;
  const template = dict[key] ?? DICT.de[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (params[name] === undefined ? `{${name}}` : String(params[name])));
}

export function formatDate(iso, lang = current) {
  if (!iso || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return '';
  const [y, m, d] = iso.split('-');
  return `${d}.${m}.${y}`.replace(/^(\d+)\.(\d+)\.(\d+)$/, lang === 'fr' ? '$1/$2/$3' : '$1.$2.$3');
}

